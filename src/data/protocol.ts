export interface ProtocolMessage {
  id: string;
  type: 'request' | 'response' | 'notification' | 'error';
  direction: 'client-to-server' | 'server-to-client';
  method: string;
  label: string;
  description: string;
  tokenCost: number;
  latencyMs: number;
  payload?: string;
  failure?: {
    type: 'timeout' | 'error' | 'context_overflow' | 'wrong_tool';
    message: string;
  };
}

